"""``source_urls`` — turning a passage's ``(source_id, slug)`` into a link.

Runs against the real ``services/data/ingest.lock.jsonl`` as well as
fixtures: the lock file is tracked precisely so this mapping stays
reproducible, and a test that only ever saw fixtures would not notice the
real one moving or changing shape.
"""

from __future__ import annotations

from pathlib import Path

from herhealth_data.retrieval.source_urls import load_source_urls

REPO = Path(__file__).resolve().parents[3]
REAL_LOCK = REPO / "services" / "data" / "ingest.lock.jsonl"


def test_a_missing_lock_file_degrades_rather_than_raising(tmp_path: Path) -> None:
    """A citation without a link is degraded; a retrieval service that will
    not start because a provenance file moved is worse."""
    assert load_source_urls(tmp_path / "absent.jsonl") == {}


def test_comment_lines_are_skipped(tmp_path: Path) -> None:
    lock = tmp_path / "ingest.lock.jsonl"
    lock.write_text(
        "# Generated by `make fetch`. Do not edit.\n"
        "# raw/ is gitignored.\n"
        '{"source_id": "nhs", "slug": "endometriosis", "url": "https://example.test/e"}\n',
        encoding="utf-8",
    )
    assert load_source_urls(lock) == {("nhs", "endometriosis"): "https://example.test/e"}


def test_one_unreadable_row_does_not_cost_the_others_their_links(tmp_path: Path) -> None:
    lock = tmp_path / "ingest.lock.jsonl"
    lock.write_text(
        '{"source_id": "nhs", "slug": "a", "url": "https://example.test/a"}\n'
        "{not json at all\n"
        '{"source_id": "cdc", "slug": "no_url_key"}\n'
        '{"source_id": "cdc", "slug": "b", "url": "https://example.test/b"}\n',
        encoding="utf-8",
    )
    index = load_source_urls(lock)
    assert index == {
        ("nhs", "a"): "https://example.test/a",
        ("cdc", "b"): "https://example.test/b",
    }


def test_the_real_lock_file_resolves_every_row_to_an_http_url() -> None:
    index = load_source_urls(REAL_LOCK)
    assert index, "the tracked ingest lock should not be empty"
    assert all(url.startswith("https://") for url in index.values())
    # Keyed on exactly what a Passage carries, which is the whole point.
    assert ("medlineplus", "pcos") in index
